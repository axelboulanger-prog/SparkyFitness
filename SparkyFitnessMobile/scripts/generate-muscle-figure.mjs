#!/usr/bin/env node
// Builds src/components/exerciseStats/muscleFigurePaths.ts from the web's
// body-map SVGs, so the phone draws the same figures the web tints.
//
// react-native-svg's SvgXml renders a whole document as one element, which
// cannot tell which muscle was tapped. The mobile figure draws one <Path> per
// region instead, and this is where those paths come from.
//
//   node scripts/generate-muscle-figure.mjs          write the module
//   node scripts/generate-muscle-figure.mjs --check  fail if it is stale
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const mobileRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..'
);
const FIGURES = ['male', 'female'];
const sourceFor = (figure) =>
  path.resolve(
    mobileRoot,
    `../SparkyFitnessFrontend/public/images/muscle-${figure}.svg`
  );
const TARGET = path.resolve(
  mobileRoot,
  'src/components/exerciseStats/muscleFigurePaths.ts'
);

function attribute(tag, name) {
  const match = tag.match(new RegExp(`\\s${name}="([^"]*)"`));
  return match ? match[1] : null;
}

function readFigure(name, svg) {
  const viewBox = attribute(svg.match(/<svg[\s\S]*?>/)?.[0] ?? '', 'viewBox');
  if (!viewBox) throw new Error(`muscle-${name}.svg has no viewBox`);

  const paths = [];
  for (const [tag] of svg.matchAll(/<path[\s\S]*?\/>/g)) {
    const d = attribute(tag, 'd');
    if (!d) continue;
    paths.push({
      svgClass: attribute(tag, 'class'),
      // Unclassed paths with a visible stroke are body outlines (the male
      // figure's front and back). Everything else is a filled region.
      outline: Number(attribute(tag, 'stroke-width') ?? '0') > 0,
      d: d.replace(/\s+/g, ' ').trim(),
    });
  }
  if (paths.length === 0) throw new Error(`muscle-${name}.svg has no paths`);
  return { viewBox, paths };
}

export function renderMuscleFigureModule(svgs) {
  const figures = FIGURES.map((name) => {
    const { viewBox, paths } = readFigure(name, svgs[name]);
    const rows = paths.map((p) => `      ${JSON.stringify(p)},`).join('\n');
    return `  ${name}: {
    viewBox: ${JSON.stringify(viewBox)},
    paths: [
${rows}
    ],
  },`;
  }).join('\n');
  return `/**
 * GENERATED by scripts/generate-muscle-figure.mjs from
 * SparkyFitnessFrontend/public/images/muscle-{male,female}.svg.
 * Do not edit by hand; run pnpm run muscle-figure:generate.
 */
import type { BodyFigure } from '@workspace/shared';

export interface MuscleFigurePath {
  /** Region class from the SVG, mapped by svgClassToSchemaName. */
  svgClass: string | null;
  /** Body (outline, head, hands, feet), drawn untinted. */
  outline: boolean;
  d: string;
}

export interface MuscleFigureDrawing {
  viewBox: string;
  paths: readonly MuscleFigurePath[];
}

export const MUSCLE_FIGURES: Record<BodyFigure, MuscleFigureDrawing> = {
${figures}
};
`;
}

function main() {
  const check = process.argv.includes('--check');
  const next = renderMuscleFigureModule(
    Object.fromEntries(
      FIGURES.map((name) => [name, fs.readFileSync(sourceFor(name), 'utf8')])
    )
  );
  const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
  if (check) {
    if (current !== next) {
      console.error(
        `${path.relative(mobileRoot, TARGET)} is out of date with the muscle SVGs. Run pnpm run muscle-figure:generate.`
      );
      process.exit(1);
    }
    return;
  }
  if (current !== next) fs.writeFileSync(TARGET, next);
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main();
}
